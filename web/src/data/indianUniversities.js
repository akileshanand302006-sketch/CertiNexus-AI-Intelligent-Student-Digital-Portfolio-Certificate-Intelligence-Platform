/**
 * Filter institutions based on user query
 */
export function searchInstitutions(query, limit = 50) {
  if (!query || !query.trim()) {
    return INDIAN_INSTITUTIONS.slice(0, limit)
  }
  const q = query.toLowerCase().trim()
  return INDIAN_INSTITUTIONS.filter((inst) =>
    inst.toLowerCase().includes(q)
  ).slice(0, limit)
}
